#!/usr/bin/env node
// scripts/init-project.mjs — 1-Command Project Bootstrapper & Multi-Reference Recipe Compiler
// Generates active DESIGN.md, ui-spec.yaml, and recipes/ui-recipe.yaml at the project root for any domain!

import fs from "node:fs";
import path from "node:path";

const args = process.argv.slice(2);
function getArg(flag, fallback = "") {
  const idx = args.indexOf(flag);
  return idx !== -1 && args[idx + 1] ? args[idx + 1] : fallback;
}

const ARCHETYPE_MAP = {
  "01": "01-b2b-fintech-precision",
  "b2b": "01-b2b-fintech-precision",
  "fintech": "01-b2b-fintech-precision",
  "02": "02-art-editorial-atelier",
  "art": "02-art-editorial-atelier",
  "editorial": "02-art-editorial-atelier",
  "03": "03-spatial-webgl-flagship",
  "webgl": "03-spatial-webgl-flagship",
  "3d": "03-spatial-webgl-flagship",
  "04": "04-tactile-consumer-app",
  "app": "04-tactile-consumer-app",
  "zomato": "04-tactile-consumer-app",
  "mobile": "04-tactile-consumer-app",
  "05": "05-luxury-commerce-editorial",
  "luxury": "05-luxury-commerce-editorial",
  "commerce": "05-luxury-commerce-editorial",
  "06": "06-agentic-command-workspace",
  "agent": "06-agentic-command-workspace",
  "ai": "06-agentic-command-workspace",
  "07": "07-kinetic-brutalist-experimental",
  "brutalist": "07-kinetic-brutalist-experimental",
  "08": "08-interactive-gaming-esports",
  "gaming": "08-interactive-gaming-esports",
  "09": "09-architecture-industrial-minimal",
  "architecture": "09-architecture-industrial-minimal",
  "10": "10-creator-media-scrollytelling",
  "media": "10-creator-media-scrollytelling"
};

const rawPrimary = getArg("--archetype", "");
const rawSecondary = getArg("--secondary", "03-spatial-webgl-flagship");
const projectName = getArg("--name", "Flagship Atlas Project");
const vision = getArg("--vision", "High-craft, zero-slop interface engineered with Design Motion Atlas v4.0.");

if (!rawPrimary) {
  console.log(`
Design Motion Atlas v4.0 — Project Bootstrapper & Recipe Compiler
=================================================================
Usage:
  npm run init:project -- --name "Project Name" --archetype <slug-or-short-code> [--secondary <slug>] [--vision "Product vision"]

Available Archetypes:
  01 | b2b          -> 01-b2b-fintech-precision (SaaS, Fintech, Analytics, DevTools)
  02 | art          -> 02-art-editorial-atelier (Art Galleries, Studios, Portfolios)
  03 | webgl        -> 03-spatial-webgl-flagship (3D Launches, Shaders, Scrollytelling)
  04 | app / zomato -> 04-tactile-consumer-app (Mobile/Web Super-Apps, Food, Social)
  05 | luxury       -> 05-luxury-commerce-editorial (High Fashion, Bespoke E-Commerce)
  06 | agent        -> 06-agentic-command-workspace (AI Copilots, AG-UI / A2UI Canvases)
  07 | brutalist    -> 07-kinetic-brutalist-experimental (Indie Culture, Music, Zines)
  08 | gaming       -> 08-interactive-gaming-esports (Esports HUDs, Game Worlds)
  09 | architecture -> 09-architecture-industrial-minimal (Architecture, Hardware)
  10 | media        -> 10-creator-media-scrollytelling (Journalism, Audio/Video Essays)

Example:
  npm run init:project -- --name "Aether Atelier" --archetype art --secondary webgl --vision "Interactive 3D architectural monograph"
`);
  process.exit(0);
}

const primarySlug = ARCHETYPE_MAP[rawPrimary.toLowerCase()] || rawPrimary;
const secondarySlug = ARCHETYPE_MAP[rawSecondary.toLowerCase()] || rawSecondary;

const archDir = path.join(process.cwd(), "archetypes", primarySlug);
if (!fs.existsSync(archDir)) {
  console.error(`[ERROR] Unknown archetype "${rawPrimary}". Run \`npm run init:project\` without arguments to see all 10 options.`);
  process.exit(1);
}

// 1. Copy active archetype's DESIGN.md and ui-spec.yaml to root so AI agents see them immediately
fs.copyFileSync(path.join(archDir, "DESIGN.md"), path.join(process.cwd(), "DESIGN.md"));
fs.copyFileSync(path.join(archDir, "ui-spec.yaml"), path.join(process.cwd(), "ui-spec.yaml"));

// 2. Generate active recipes/ui-recipe.yaml tailored to the project
const recipeOut = `# recipes/ui-recipe.yaml — Active Project Multi-Reference DNA Recipe (Generated by init-project.mjs)
project:
  name: ${JSON.stringify(projectName)}
  user_vision: ${JSON.stringify(vision)}
  primary_archetype: ${JSON.stringify(primarySlug)}
  secondary_archetype: ${JSON.stringify(secondarySlug)}
  html_data_attribute: 'data-archetype="${primarySlug}"'

dna_mixing_protocol:
  mandate: "Blend 4 independent atomic layers from reference-index/curated-sources.yaml + custom-sources.yaml. Never copy a single site 1:1."
  layer_1_spatial_grid: "Use ${primarySlug} grid geometry and whitespace ratio locked in root DESIGN.md."
  layer_2_typography: "Use 100% free commercial fonts declared in root ui-spec.yaml (Fontshare / UNCUT.wtf / Velvetyne)."
  layer_3_motion_physics: "Use Scroll & Spring choreography from motion-specs/ and blocks/."
  layer_4_signature_hook: "Select 1 bespoke interactive centerpiece from recipes/signature-hooks-library.md."
`;

fs.writeFileSync(path.join(process.cwd(), "recipes", "ui-recipe.yaml"), recipeOut, "utf8");

console.log(`\n[ATLAS PROJECT INITIALIZED]`);
console.log(`  - Project Name       : ${projectName}`);
console.log(`  - Primary Archetype  : ${primarySlug} (copied to root DESIGN.md & ui-spec.yaml)`);
console.log(`  - Secondary Blend    : ${secondarySlug}`);
console.log(`  - Active DNA Recipe  : recipes/ui-recipe.yaml`);
console.log(`  - HTML Theme Lock    : Set <html data-archetype="${primarySlug}"> in your root layout.\n`);
